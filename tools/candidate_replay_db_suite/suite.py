#!/usr/bin/env python3
"""Scratch reproduction: ml_generated_candidates replay vs the LIVE RLS shape (read-only capture 21 Oct 2026 10:3x IST).

Live (BEGIN READ ONLY catalog read, project fdynxkfxohbnlvayouje, PostgreSQL 17.6):
  RLS enabled (not forced); policies: "allow anon insert" INSERT TO anon WITH CHECK (true),
  "allow anon select" SELECT TO anon USING (true); NO UPDATE/DELETE policy.
  Grants: anon INSERT,REFERENCES,SELECT,TRIGGER,UPDATE; authenticated DELETE,INSERT,REFERENCES,SELECT,TRIGGER,UPDATE.
  Unique index idx_ml_generated_candidates_poll_candidate (snapshot_poll_ts, candidate_id); pkey id (identity BY DEFAULT);
  no triggers; owner postgres.
This suite recreates exactly that shape in a scratch database, drives it through PostgREST 12.2.3 with the request
shapes the app uses, and records every response into app/src/test/resources/candidate_replay/postgrest_golden.json.
The JVM replay tests consume that file, so the Kotlin reconciler is tested against real PostgREST behaviour.
Default mode checks the committed golden (status + parsed body); --write regenerates it. Synthetic fixture only.
"""
import json
import os
import sys
import urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 's1a_db_suite'))
os.environ.setdefault('S1A_SCRATCH_OK', '1')
import suite as S  # noqa: E402  (scratch helpers: roles, psql, PostgREST runner)

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
GOLDEN = os.path.join(ROOT, 'app', 'src', 'test', 'resources', 'candidate_replay', 'postgrest_golden.json')
DB = 'candidate_replay_%d' % os.getpid()
TABLE = 'ml_generated_candidates'

COLUMNS = [  # capture-written columns, order = GeneratedCohort.COLUMNS
    ('snapshot_poll_ts', 'timestamptz not null'), ('session_date', 'date'), ('recommendation_id', 'text'),
    ('quality_tag', 'text'), ('decision_source', 'text'), ('candidate_id', 'text not null'), ('lane', 'text'),
    ('index_key', 'text'), ('strategy_type', 'text'), ('trade_mode', 'text'), ('rank', 'integer'),
    ('watchlist_rank', 'integer'), ('was_surfaced', 'boolean not null default false'), ('net_premium', 'double precision'),
    ('max_profit', 'double precision'), ('max_loss', 'double precision'), ('risk_reward', 'text'),
    ('premium_edge', 'double precision'), ('ev_per_1k', 'double precision'), ('est_cost', 'double precision'),
    ('capital_blocked', 'boolean'), ('width', 'integer'), ('expiry', 'text'), ('sigma_otm', 'double precision'),
    ('iv_richness', 'double precision'), ('credit_width_ratio', 'double precision'), ('is_credit', 'boolean'),
    ('execution_ready', 'boolean'), ('execution_gate', 'text'), ('entry_action', 'text'), ('direction_safe', 'boolean'),
    ('brain_score', 'double precision'), ('p_ml', 'double precision'), ('ml_action', 'text'), ('ml_edge', 'double precision'),
    ('ml_regime', 'text'), ('ml_unsure', 'boolean'), ('ml_ood_flag', 'boolean'),
    ('signal_independence_score', 'double precision'), ('generated_count', 'integer'), ('watchlist_count', 'integer'),
    ('app_version', 'text'), ('brain_version', 'text')]
NAMES = [c for c, _ in COLUMNS]

DDL = """
create table public.%(t)s (
  id bigint generated by default as identity primary key,
  %(cols)s,
  created_at timestamptz not null default now()
);
create unique index idx_ml_generated_candidates_poll_candidate on public.%(t)s (snapshot_poll_ts, candidate_id);
alter table public.%(t)s enable row level security;
create policy "allow anon insert ml_generated_candidates" on public.%(t)s for insert to anon with check (true);
create policy "allow anon select ml_generated_candidates" on public.%(t)s for select to anon using (true);
grant insert, references, select, trigger, update on public.%(t)s to anon;
grant delete, insert, references, select, trigger, update on public.%(t)s to authenticated;
grant usage on schema public to anon, authenticated;
""" % {'t': TABLE, 'cols': ',\n  '.join('%s %s' % c for c in COLUMNS)}

POLL_TS = '2026-10-19T10:15:00+05:30'      # synthetic; IST offset as the phone writes it


def fixture_rows():
    rows = []
    for i in range(50):
        ix = 'NF' if i % 2 == 0 else 'BNF'
        rows.append({
            'snapshot_poll_ts': POLL_TS, 'session_date': '2026-10-19', 'recommendation_id': 'rec-fixture-1015',
            'quality_tag': 'fixture', 'decision_source': 'generated', 'candidate_id': 'FX-%s-%03d' % (ix, i),
            'lane': ix + '_intraday', 'index_key': ix, 'strategy_type': ['BULL_PUT', 'BEAR_CALL', 'IRON_CONDOR'][i % 3],
            'trade_mode': 'intraday', 'rank': i + 1, 'watchlist_rank': (i + 1) if i < 5 else None, 'was_surfaced': i < 5,
            'net_premium': round(10 + i * 0.37, 2), 'max_profit': 1000.0 + i, 'max_loss': -(2500.5 + i), 'risk_reward': '1:%d' % (2 + i % 3),
            'premium_edge': 0.1 * (i % 7), 'ev_per_1k': [1.0, 0.1, -0.0, 12.345678901234567, 3e-05][i % 5],
            'est_cost': 40.0 + i, 'capital_blocked': False, 'width': 100 if ix == 'NF' else 200, 'expiry': '2026-10-27',
            'sigma_otm': 0.85 + i / 1000.0, 'iv_richness': None if i % 4 == 0 else 1.05, 'credit_width_ratio': 0.33,
            'is_credit': True, 'execution_ready': i % 2 == 0, 'execution_gate': 'PAPER_ONLY', 'entry_action': 'WAIT',
            'direction_safe': True, 'brain_score': 0.5 + i / 100.0, 'p_ml': 0.61, 'ml_action': 'HOLD', 'ml_edge': 0.02,
            'ml_regime': 'RANGE', 'ml_unsure': False, 'ml_ood_flag': False, 'signal_independence_score': 0.7,
            'generated_count': 200, 'watchlist_count': 5, 'app_version': '2.6.79', 'brain_version': '2.6.79'})
    return rows


UPSERT = TABLE + '?on_conflict=snapshot_poll_ts,candidate_id'           # app path at 2.6.80
UPSERT_PREFER = 'resolution=merge-duplicates,return=minimal'
INSERT = TABLE                                                           # repair: plain INSERT, never UPDATE
INSERT_PREFER = 'return=minimal'


def readback_path(poll_ts):
    # Must equal GeneratedCandidateReplay.readBackPath (asserted by the JVM test against this golden).
    # float8 columns are read as ::text: JSON number parsing (Python, Android org.json) turns "-0" into integer 0
    # and would lose the sign that the generated_row_witness_v2 contract keeps; Postgres text is exact round-trip.
    sel = ','.join(c + '::text' if t.startswith('double') else c for c, t in COLUMNS)
    return '%s?select=%s&snapshot_poll_ts=eq.%s&order=candidate_id.asc&limit=1000' % (
        TABLE, sel, urllib.parse.quote(poll_ts, safe=''))


def count():
    return int(S.val('select count(*) from public.%s' % TABLE, DB, user='postgres'))


def reset():
    S.psql('truncate public.%s restart identity;' % TABLE, DB, user='postgres')


def main(argv):
    write = '--write' in argv
    binary = os.environ.get('CANDIDATE_POSTGREST_BIN') or os.environ.get('S1A_POSTGREST_BIN')
    if os.environ.get('CANDIDATE_SCRATCH_OK') != '1' or not binary:
        print('refusing: CANDIDATE_SCRATCH_OK=1 and CANDIDATE_POSTGREST_BIN are required (scratch only)', file=sys.stderr)
        return 2
    S.psql(S.ROLES_SQL, 'postgres')
    S.psql("alter role authenticator login password '%s';" % S.AUTH_PW, 'postgres')
    S.psql('drop database if exists %s;' % DB, 'postgres')
    S.psql('create database %s owner postgres;' % DB, 'postgres')
    S.psql('alter schema public owner to postgres;', DB)
    # Deterministic like live Supabase (UTC): timestamptz read-backs then carry +00:00 on every host.
    S.psql("alter database %s set timezone to 'UTC';" % DB, 'postgres')
    S.psql(DDL, DB, user='postgres')
    rows = fixture_rows()
    first, rest = rows[:25], rows[25:]
    rec = {}
    rest_api = S.Rest(DB, binary)
    try:
        def call(name, method, path, role, body=None, prefer=None):
            status, text = rest_api.call(method, path, role, body, prefer)
            rec[name] = {'method': method, 'path': path, 'role': role, 'prefer': prefer, 'status': status,
                         'body': json.loads(text) if text.strip() else None}
            return status, rec[name]['body']

        # --- 2.6.80 behaviour: merge-duplicates upsert under the live policies
        s, _ = call('upsert_new', 'POST', UPSERT, 'anon', rows, UPSERT_PREFER)
        S.check('live shape: merge-duplicates upsert of a NEW cohort succeeds (201)', s == 201 and count() == 50)
        s, b = call('upsert_repeat', 'POST', UPSERT, 'anon', rows, UPSERT_PREFER)
        S.check('live shape: repeating the SAME frozen cohort -> 401 42501 "(USING expression)" (exact live error)',
                s == 401 and b.get('code') == '42501' and '(USING expression)' in b.get('message', ''), b)
        S.check('  ... and nothing changed (still 50 rows)', count() == 50)
        reset(); call('seed_first_half_plain', 'POST', INSERT, 'anon', first, INSERT_PREFER)
        s, b = call('upsert_partial', 'POST', UPSERT, 'anon', rows, UPSERT_PREFER)
        S.check('live shape: upsert of a PARTIALLY present cohort -> 401 42501 USING; atomic (25 rows remain)',
                s == 401 and b.get('code') == '42501' and count() == 25, b)
        # --- repair primitives: plain INSERT + SELECT read-back (no UPDATE policy or grant needed)
        reset()
        s, _ = call('insert_new', 'POST', INSERT, 'anon', rows, INSERT_PREFER)
        S.check('repair: plain INSERT of a new cohort -> 201', s == 201 and count() == 50)
        s, b = call('insert_repeat', 'POST', INSERT, 'anon', rows, INSERT_PREFER)
        S.check('repair: plain INSERT of an already-committed cohort -> 409 23505 (not an RLS error); unchanged',
                s == 409 and b.get('code') == '23505' and count() == 50, b)
        s, b = call('readback_full', 'GET', readback_path(POLL_TS), 'anon')
        S.check('repair: anon SELECT read-back returns all 50 rows in candidate_id order', s == 200 and len(b) == 50
                and [r['candidate_id'] for r in b] == sorted(r['candidate_id'] for r in rows))
        S.check('repair: read-back exposes only capture-written columns (no id/created_at)',
                all(set(r) == set(NAMES) for r in b))
        S.check('repair: float8 read back as exact text keeps -0 (sign) and shortest round-trip digits',
                {r['candidate_id']: r['ev_per_1k'] for r in b}['FX-NF-002'] == '-0'
                and {r['candidate_id']: r['ev_per_1k'] for r in b}['FX-BNF-003'] == '12.345678901234567', b[:1])
        reset()
        call('seed_first_half_plain_2', 'POST', INSERT, 'anon', first, INSERT_PREFER)
        s, b = call('insert_partial', 'POST', INSERT, 'anon', rows, INSERT_PREFER)
        S.check('repair: plain INSERT of a partially present cohort -> 409 23505, atomic (25 rows remain)',
                s == 409 and b.get('code') == '23505' and count() == 25, b)
        s, b = call('readback_partial', 'GET', readback_path(POLL_TS), 'anon')
        S.check('repair: read-back of the partial cohort returns exactly the 25 present rows', s == 200 and len(b) == 25)
        s, _ = call('insert_missing', 'POST', INSERT, 'anon', rest, INSERT_PREFER)
        S.check('repair: INSERT of only the 25 absent rows -> 201; cohort complete (50)', s == 201 and count() == 50)
        s, b = call('readback_after_completion', 'GET', readback_path(POLL_TS), 'anon')
        S.check('repair: read-back after completion returns 50 rows', s == 200 and len(b) == 50)
        S.psql("update public.%s set ev_per_1k = 99.5 where candidate_id = 'FX-NF-010';" % TABLE, DB, user='postgres')
        s, b = call('readback_conflict', 'GET', readback_path(POLL_TS), 'anon')
        S.check('conflict fixture: one stored row differs (ev_per_1k on FX-NF-010)', s == 200 and len(b) == 50 and any(
            r['candidate_id'] == 'FX-NF-010' and r['ev_per_1k'] == '99.5' for r in b))
        s, b = call('anon_patch_attempt', 'PATCH', TABLE + '?candidate_id=eq.FX-NF-010', 'anon', {'ev_per_1k': 1.0},
                    'return=representation')
        S.check('no UPDATE policy: anon PATCH matches 0 rows despite the UPDATE grant (stored row not overwritten)',
                s == 200 and b == [] and S.val("select ev_per_1k from public.%s where candidate_id='FX-NF-010'" % TABLE,
                                               DB, user='postgres') == '99.5', (s, b))
        # --- role sensitivity (G1 session flag would send an authenticated JWT; no policy exists for it)
        reset()
        s, b = call('auth_insert', 'POST', INSERT, 'authenticated', rows, INSERT_PREFER)
        S.check('authenticated role: plain INSERT -> 403 42501 (no INSERT policy for authenticated); nothing written',
                s == 403 and b.get('code') == '42501' and count() == 0, b)
        call('seed_full_for_auth_readback', 'POST', INSERT, 'anon', rows, INSERT_PREFER)
        s, b = call('auth_readback', 'GET', readback_path(POLL_TS), 'authenticated')
        S.check('authenticated role: read-back sees [] (no SELECT policy) -> reconciler must not acknowledge',
                s == 200 and b == [])
    finally:
        rest_api.close()
        S.psql('drop database if exists %s;' % DB, 'postgres')
    doc = {'schema': 'candidate_replay_postgrest_golden_v1', 'postgrest': '12.2.3', 'poll_ts': POLL_TS,
           'upsert_path': UPSERT, 'upsert_prefer': UPSERT_PREFER, 'insert_path': INSERT, 'insert_prefer': INSERT_PREFER,
           'readback_path': readback_path(POLL_TS), 'envelope': {'poll_ts': POLL_TS, 'rows': rows}, 'responses': rec}
    if write:
        with open(GOLDEN, 'w') as fh:
            json.dump(doc, fh, indent=1, sort_keys=True); fh.write('\n')
        print('WROTE', os.path.relpath(GOLDEN, ROOT))
    else:
        old = json.load(open(GOLDEN))
        S.check('committed golden equals this run (status + parsed bodies + paths)', old == json.loads(json.dumps(doc)),
                'run with --write to inspect the difference')
    failed = [n for n, ok in S.results if not ok]
    print('%d checks, %d failed' % (len(S.results), len(failed)))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
