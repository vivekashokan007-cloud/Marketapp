package com.marketradar.app

import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.nio.file.Files

/**
 * END TO END, through the real poll mapping and the real export assembly.
 *
 * What this class produces is the input to the Stage G matcher: a PHONE-SHAPED export, carrying
 * the frozen pilot stream under `premium` and the follow-on research stream under
 * `premium_followon`, for both indices, on two adjacent sessions. It is assembled here exactly
 * as `NativeBridge.saveSessionEvidence` assembles it — `PremiumExportSection.build` for the
 * pilot, `PremiumFollowOnCapture.exportSection` for the research stream, each spliced under its
 * own key through `mergeWithinCap` — and the result is written to the committed fixtures the
 * Python matcher and ledger read.
 *
 * THE DEFECT THIS SHAPE EXPOSED. The matcher read `premium` unconditionally. On an export of
 * this shape it therefore read the PILOT stream, which carries valid quotes for DIFFERENT
 * contracts, found no overnight pairing in it, and reported zero pairs for both indices with no
 * refusal reason at all. The two streams must be named apart, and this fixture is what proves
 * they are: the pilot cohort here is deliberately a different set of strikes from the
 * follow-on's carried cohort, so pointing at the wrong section cannot accidentally succeed.
 *
 * Coverage, each asserted below: both indices; a restart between the close and the reopen (the
 * reopen runs on fresh objects that must read the carry from disk); a switched instrument key;
 * an expiry roll; and a missing follow-on section. The regenerated bytes are compared with the
 * committed fixture, so the cross-language evidence cannot silently drift — set
 * `PREMIUM_WRITE_FIXTURES=1` to rewrite it deliberately.
 */
class PremiumFollowOnEndToEndTest {

    private val friday = "2026-10-16"
    private val monday = "2026-10-19"
    /**
     * The acquisition clocks for one slot, in IST, on the session's own date.
     *
     * These are what the matcher measures everything on: a receipt that does not belong to the
     * session it claims is refused as `receipt_date_not_in_session`, so a generator that stamps
     * one fixed instant on every slot produces an export in which nothing can be scored. The
     * request starts 5 s before the response, as the real path records it.
     */
    private fun respMsFor(date: String, clock: String): Long {
        val (y, mo, d) = date.split("-").map { it.toInt() }
        val (h, mi) = clock.split(":").map { it.toInt() }
        return java.time.ZonedDateTime.of(y, mo, d, h, mi, 7, 0,
            java.time.ZoneId.of("Asia/Kolkata")).toInstant().toEpochMilli()
    }

    private fun reqMsFor(date: String, clock: String) = respMsFor(date, clock) - 5_000L

    private fun raw(id: String): JSONObject {
        val text = requireNotNull(
            javaClass.classLoader?.getResourceAsStream("contracts/x1_upstox_raw_chains.json"))
            .bufferedReader().readText()
        val snaps = JSONObject(text).getJSONArray("snapshots")
        for (i in 0 until snaps.length()) {
            val s = snaps.getJSONObject(i)
            if (s.optString("id") == id) return s.getJSONObject("raw")
        }
        throw AssertionError("fixture snapshot $id not found")
    }

    private fun researchDir(name: String): File {
        val d = Files.createTempDirectory(name).toFile().apply { mkdirs() }
        PremiumCaptureControl.setEnabled(d, true)
        assertTrue(PremiumFollowOnCapture.setResearchEnabled(d, true))
        return d
    }

    /** One pilot slot, through the frozen pilot path, with its own free cohort selection. */
    private fun pilot(filesDir: File, index: String, date: String, clock: String,
                      chainId: String): PremiumCaptureSession.SlotResult {
        val store = PremiumCaptureStore(PremiumCaptureControl.root(filesDir))
        return PremiumCaptureSession(store).observeSlot(
            index, date, raw(chainId), clock, clock,
            PremiumCaptureCohort.INDEX_UNDERLYING[index],
            reqMsFor(date, clock), respMsFor(date, clock),
            claimedLot = if (index == "NF") 75 else 35,
            claimedLotSource = "CONTRACT_LOT_TABLE",
            lotTableRef = "contract_lot_table/contract_lot_table_v3_20260914/TEST/$date")
    }

    private fun expiryOf(chain: JSONObject): String =
        chain.getJSONArray("data").getJSONObject(0).getString("expiry")

    /**
     * One follow-on slot THROUGH THE REAL POLL MAPPING: the chain is handed to
     * `PremiumCapturePollAdapter.acquisitions`, exactly as `MarketWatchService` does, and every
     * argument the capture receives comes from the resulting `ChainAcquisition`.
     *
     * This is not decoration. `expiryForAuthority` is what makes the capture resolve and write
     * the production lot authority, and the first version of this test supplied it by hand and
     * forgot it — producing a tree whose envelopes pointed at a `production_authority_ref` with
     * no record behind it, so Stage D refused all 12 rows `lot_authority_unresolved`. Going
     * through the adapter means the test cannot diverge from the poll on that field again.
     */
    private fun followOn(filesDir: File, index: String, date: String, clock: String,
                         chainId: String, chainOverride: JSONObject? = null):
        PremiumFollowOnCapture.Attempt {
        val chain = chainOverride ?: raw(chainId)
        val acq = PremiumCapturePollAdapter.acquisitions(listOf(
            PremiumCapturePollAdapter.IndexResult(
                index = index, chain = chain,
                requestStartedMs = reqMsFor(date, clock),
                completedAtMs = respMsFor(date, clock),
                underlyingKey = PremiumCaptureCohort.INDEX_UNDERLYING[index],
                expiry = expiryOf(chain)))).single()
        assertEquals("the adapter must derive this slot's clock", clock, acq.receiptHhmm)
        return PremiumFollowOnCapture.observe(
            filesDir = filesDir, index = acq.index, sessionDate = date,
            rawChain = acq.rawChain, acquisitionHhmm = acq.receiptHhmm, schedulerSlot = clock,
            requestedUnderlyingKey = acq.requestedUnderlyingKey,
            requestStartedMs = acq.requestStartedMs,
            responseReceivedMs = acq.responseReceivedMs,
            vendorSourceTs = acq.vendorSourceTs,
            declaredSchedulerSlot = clock,
            expiryForAuthority = acq.expiry)
    }

    /**
     * The export assembly, mirroring `NativeBridge` step for step: the pilot section first, the
     * research section second and under its own key, the pilot never truncated for it.
     */
    private fun assembleAsTheBridgeDoes(filesDir: File, date: String): Pair<JSONObject, Boolean> {
        val bundle = JSONObject()
            .put("manifest", JSONObject().put("status", "OK").put("session_date_used", date)
                .put("session_date_requested", date))
            .toString()
        val premium = PremiumExportSection.build(filesDir, date)
        var fit = PremiumExportSection.mergeWithinCap(
            bundle, bundle.toByteArray(Charsets.UTF_8), premium)
        assertTrue("the pilot section must fit", fit.merged && !fit.overCap)
        var followOnMerged = false
        if (PremiumFollowOnCapture.isResearchEnabled(filesDir)) {
            val followOn = PremiumFollowOnCapture.exportSection(filesDir, date)
            if (!fit.overCap) {
                val both = PremiumExportSection.mergeWithinCap(
                    String(fit.bytes, Charsets.UTF_8), fit.bytes, followOn, "premium_followon")
                if (both.merged && !both.overCap) {
                    fit = both
                    followOnMerged = true
                }
            }
        }
        return JSONObject(String(fit.bytes, Charsets.UTF_8)) to followOnMerged
    }

    private fun strikesOf(section: JSONObject, index: String): List<Double> {
        val node = section.getJSONObject("indices").getJSONObject(index)
        val pinned = node.getJSONObject("cohort").getJSONArray("pinned_contracts")
        return (0 until pinned.length())
            .map { pinned.getJSONObject(it).getDouble("strike") }
            .distinct().sorted()
    }

    // ───────────────────────── the phone-shaped export, both sessions ─────────────────────────

    /**
     * Build both sessions through the real paths, then WRITE the committed fixtures the Python
     * side reads, and assert everything the two sections must keep apart.
     */
    @Test
    fun theTwoStreamsAreAssembledApartForBothIndicesAcrossARestart() {
        // ── session one: the close ───────────────────────────────────────────────────────────
        val day1 = researchDir("e2e-close")
        for (index in listOf("NF", "BNF")) {
            // the pilot runs its own window on its own cohort, chosen freely around a spot that
            // is NOT the close spot, so its contracts differ from the follow-on's
            for ((clock, chain) in listOf(
                "09:20" to "mon_0951_primary_exit_$index", "15:00" to "mon_0956_control_exit_$index")) {
                assertEquals("pilot $index $clock", PremiumCaptureSession.OBSERVED,
                    pilot(day1, index, friday, clock, chain).status)
            }
            assertEquals("follow-on close $index", PremiumCaptureSession.OBSERVED,
                followOn(day1, index, friday, "15:20", "fri_1520_reference_$index")
                    .slotResult?.status)
        }
        val (doc1, merged1) = assembleAsTheBridgeDoes(day1, friday)
        assertTrue("the research section must be merged", merged1)

        // the two streams are present, named apart, and carry DIFFERENT contracts
        val pilot1 = doc1.getJSONObject("premium")
        val follow1 = doc1.getJSONObject("premium_followon").getJSONObject("section")
        for (index in listOf("NF", "BNF")) {
            assertNotEquals("the pilot cohort must not be the follow-on's for $index",
                strikesOf(pilot1, index), strikesOf(follow1, index))
        }
        assertEquals(PremiumFollowOnCapture.PURPOSE,
            doc1.getJSONObject("premium_followon").getString("purpose"))
        assertEquals("OK", doc1.getJSONObject("manifest").getString("status"))

        // ── RESTART: the reopen runs on fresh objects, reading the carry from disk ───────────
        val day2 = day1            // the same files dir, as a device restart would leave it
        for (index in listOf("NF", "BNF")) {
            // a cohort chosen around a spot that is NOT the carried one, so the pilot stream
            // and the research stream share no contract on this session either
            assertEquals("pilot reopen $index", PremiumCaptureSession.OBSERVED,
                pilot(day2, index, monday, "09:20", "mon_0956_control_exit_$index").status)
            for ((clock, chain) in listOf(
                "09:20" to "mon_0920_entry_$index", "09:25" to "mon_0925_control_$index")) {
                assertEquals("follow-on reopen $index $clock", PremiumCaptureSession.OBSERVED,
                    followOn(day2, index, monday, clock, chain).slotResult?.status)
            }
        }
        val (doc2, merged2) = assembleAsTheBridgeDoes(day2, monday)
        assertTrue(merged2)
        val pilot2 = doc2.getJSONObject("premium")
        val follow2 = doc2.getJSONObject("premium_followon").getJSONObject("section")
        for (index in listOf("NF", "BNF")) {
            // the follow-on carried YESTERDAY's strikes; the pilot selected today's freely
            assertEquals("the carry must hold for $index",
                strikesOf(follow1, index), strikesOf(follow2, index))
            assertNotEquals("and the pilot must not be the same cohort for $index",
                strikesOf(pilot2, index), strikesOf(follow2, index))
        }

        // THE INVARIANT THAT MAKES THE SECTION NAME LOAD-BEARING: the pilot stream cannot
        // carry a close mark at all, whatever its cohort, because its window ends at 15:05
        // exclusive. Pointing the matcher at `premium` can therefore never produce an
        // overnight pair — it can only produce silence, which is what it did.
        for (index in listOf("NF", "BNF")) {
            val slots = pilot1.getJSONObject("indices").getJSONObject(index)
                .getJSONArray("slot_envelopes").let { a ->
                    (0 until a.length()).map { a.getJSONObject(it).getString("slot") } }
            assertTrue("the pilot captured something for $index", slots.isNotEmpty())
            for (slot in slots) {
                val m = slot.substringBefore(':').toInt() * 60 + slot.substringAfter(':').toInt()
                assertFalse("$index pilot slot $slot must be outside the close window",
                    PremiumFollowOnCapture.CLOSE_WINDOW.contains(m))
            }
        }

        writeFixture("phone_shaped_export_$friday.json", doc1, friday,
            "the close session: pilot 09:20 and 15:00 on its own cohort, follow-on close at 15:20")
        writeFixture("phone_shaped_export_$monday.json", doc2, monday,
            "the reopen session after a restart: pilot 09:20 on today's cohort, " +
                "follow-on 09:20 and 09:25 on yesterday's carried contracts")
    }

    /** A switched instrument key is refused at the reopen, not silently re-pinned. */
    @Test
    fun aSwitchedInstrumentKeyIsRefusedInTheAssembledExport() {
        val dir = researchDir("e2e-switched-key")
        assertEquals(PremiumCaptureSession.OBSERVED,
            followOn(dir, "NF", friday, "15:20", "fri_1520_reference_NF").slotResult?.status)
        // Monday's response resolves ONE carried strike to a different instrument key
        val carried = PremiumFollowOnCapture.readCarry(dir, "NF", monday).contracts
        val chain = JSONObject(raw("mon_0920_entry_NF").toString())
        val rows = chain.getJSONArray("data")
        var swapped = false
        for (i in 0 until rows.length()) {
            val row = rows.getJSONObject(i)
            if (row.optDouble("strike_price") == carried[0].strike) {
                row.getJSONObject("call_options").put("instrument_key", "NSE_FO|SWITCHED")
                swapped = true
            }
        }
        assertTrue("the fixture must carry the strike this test switches", swapped)
        val r = followOn(dir, "NF", monday, "09:20", "", chain)
        assertEquals(PremiumCaptureCohort.REQUIRED_KEY_MISMATCH, r.slotResult?.status)
        val (doc, _) = assembleAsTheBridgeDoes(dir, monday)
        val section = doc.getJSONObject("premium_followon").getJSONObject("section")
        // the refusal is PUBLISHED and the observation is not: a stated absence, not silence
        val node = section.optJSONObject("indices")?.optJSONObject("NF")
        val envelopes = node?.optJSONArray("slot_envelopes")
        assertEquals("no reopen quote may be published", 0, envelopes?.length() ?: 0)
        assertEquals(0, node?.optJSONArray("records")?.length() ?: 0)
        // the REASON is published too, as a durable counter, so the absence is stated
        val outcomes = doc.getJSONObject("premium_followon")
            .getJSONObject("window_outcomes").getJSONObject("NF")
        assertEquals(1, outcomes.optInt(
            "followon_reopen_refused_" + PremiumCaptureCohort.REQUIRED_KEY_MISMATCH))
        assertEquals(1, outcomes.optInt("followon_reopen_attempts"))
        assertEquals("no reopen quote was observed", 0,
            outcomes.optInt("followon_reopen_observed"))
    }

    /** An expiry roll is refused at the reopen: the exit-before-expiry rule. */
    @Test
    fun anExpiryRollIsRefusedInTheAssembledExport() {
        val dir = researchDir("e2e-expiry-roll")
        assertEquals(PremiumCaptureSession.OBSERVED,
            followOn(dir, "NF", friday, "15:20", "fri_1520_reference_NF").slotResult?.status)
        val chain = JSONObject(raw("mon_0920_entry_NF").toString())
        val rows = chain.getJSONArray("data")
        for (i in 0 until rows.length()) rows.getJSONObject(i).put("expiry", "2026-11-24")
        val r = followOn(dir, "NF", monday, "09:20", "", chain)
        assertEquals(PremiumCaptureCohort.REQUIRED_EXPIRY_MISMATCH, r.slotResult?.status)
    }

    /** With the research control off, the export carries the pilot stream and nothing else. */
    @Test
    fun aMissingFollowOnSectionLeavesThePilotExportExactlyAsItWas() {
        val dir = Files.createTempDirectory("e2e-no-research").toFile()
        PremiumCaptureControl.setEnabled(dir, true)
        assertFalse("the research control is off by default",
            PremiumFollowOnCapture.isResearchEnabled(dir))
        assertEquals(PremiumCaptureSession.OBSERVED,
            pilot(dir, "NF", friday, "09:20", "mon_0951_primary_exit_NF").status)
        val (doc, merged) = assembleAsTheBridgeDoes(dir, friday)
        assertFalse(merged)
        assertTrue("the pilot stream must be present", doc.has("premium"))
        assertFalse("and no research key may appear", doc.has("premium_followon"))
        assertEquals("OK", doc.getJSONObject("manifest").getString("status"))
        assertTrue(doc.getJSONObject("premium").optBoolean("has_data"))
    }

    // ───────────────────────── the committed fixture ─────────────────────────

    private fun fixtureDir(): File = listOf(
        File("src/test/resources/premium_capture"),
        File("app/src/test/resources/premium_capture"),
        File("../app/src/test/resources/premium_capture")).first { it.isDirectory }

    /**
     * Write or verify one committed fixture. The provenance block is what the Stage C input
     * inventory reads to label the file SYNTHETIC: these bytes come from the real producer, but
     * no device produced them.
     */
    private fun writeFixture(name: String, doc: JSONObject, date: String, what: String) {
        val payload = JSONObject(doc.toString())
            .put("_fixture", name.removeSuffix(".json"))
            .put("_provenance", JSONObject()
                .put("synthetic", true)
                .put("session_date", date)
                .put("produced_by", "PremiumCaptureSession.observeSlot + " +
                    "PremiumFollowOnCapture.observe, assembled as NativeBridge assembles the " +
                    "export, from contracts/x1_upstox_raw_chains.json")
                .put("produced_by_test",
                    "PremiumFollowOnEndToEndTest.theTwoStreamsAreAssembledApartForBothIndices" +
                        "AcrossARestart")
                .put("what", what)
                .put("shape", "the phone shape: the frozen pilot stream under `premium` with " +
                    "its OWN cohort, the follow-on research stream under `premium_followon`")
                .put("why", "the Stage G matcher is proved to read the named section rather " +
                    "than whichever stream happens to sit under `premium`")
                .put("note", "the sections declare LIVE_DEVICE_CAPTURE because " +
                    "PremiumExportSection uses the device context; this file is NOT a live " +
                    "capture, and this block is what labels it synthetic"))
        val text = payload.toString(1) + "\n"
        val target = File(fixtureDir(), name)
        if (System.getenv("PREMIUM_WRITE_FIXTURES") == "1" || !target.isFile) {
            target.writeText(text, Charsets.UTF_8)
            return
        }
        val committed = JSONObject(target.readText(Charsets.UTF_8))
        for (key in listOf("premium", "premium_followon", "manifest")) {
            assertEquals("$name/$key drifted from the committed fixture — regenerate with " +
                "PREMIUM_WRITE_FIXTURES=1 if the change is intended",
                committed.opt(key)?.toString(), payload.opt(key)?.toString())
        }
    }

    /** The fixtures the Python side reads must be the ones this test produces. */
    @Test
    fun theCommittedFixturesExistAndCarryBothSections() {
        for (date in listOf(friday, monday)) {
            val f = File(fixtureDir(), "phone_shaped_export_$date.json")
            if (!f.isFile) continue        // first run writes them; nothing to verify yet
            val doc = JSONObject(f.readText(Charsets.UTF_8))
            assertTrue("$date must carry the pilot stream", doc.has("premium"))
            assertTrue("$date must carry the research stream", doc.has("premium_followon"))
            assertTrue(doc.getJSONObject("_provenance").getBoolean("synthetic"))
            assertNull("no device claim may appear in a synthetic fixture",
                doc.getJSONObject("_provenance").opt("device"))
            for (index in listOf("NF", "BNF")) {
                val pilotStrikes = strikesOf(doc.getJSONObject("premium"), index)
                val followStrikes = strikesOf(
                    doc.getJSONObject("premium_followon").getJSONObject("section"), index)
                assertNotEquals("$date/$index: the two streams must carry different contracts",
                    pilotStrikes, followStrikes)
            }
        }
    }
}
